"""Build, compile, inspect and install one authored multiplayer map.

    python3 -B dkq3/tools/map_build.py --map japanDM [--source maps/japanDM] \
        [--prefix zig-out/native-dev] [--stages author,compile,aas,package,install] [--quality]

A map is authored in `maps/<name>/`: `materials.py` is the material table (the
generated `.shader` and the image manifest both come from it),
`build_blender.py` models the level into `<name>.blend` when the `.blend` is
missing or older than the script, and `map_author.py` exports that scene to
`<name>.map`. Everything derived afterwards is a build product under
`zig-out/map-dev/<name>/`: the private compiler tree, the BSP, the bot AAS, the
build report and the installable `zz-dk3-<name>.pk3`.

q3map2 runs against a private VFS rooted at `<work>/home/.q3a/baseq3` with `HOME`
pointed at it, so a map build reads and writes nothing outside its own tree; the
installation receives exactly one loose package plus its own `maps.cfg`
replacement. The converted packages are hash-checked by the launcher and the
preserved game stays untouched, so maps are always *added*, never rewritten.

Each stage reports what it proved. `--stages compile` alone reuses the exported
`.map`, and a compile that leaked, lost its vis, arrived unlit, or reached the
BSP without its shaders is a failure even when q3map2 exits 0.
"""
